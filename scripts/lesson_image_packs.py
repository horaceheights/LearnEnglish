"""Deterministic byte-for-byte still-image packs; no codec or native dependency."""
from __future__ import annotations

import hashlib
import io
import json
from pathlib import Path

from PIL import Image

BUCKETS = 64
MAX_PACK_BYTES = 8 * 1024 * 1024


def build_index(image_root: Path, names: list[str]) -> dict:
    buckets: dict[int, list[str]] = {}
    for name in sorted(set(names)):
        if Path(name).name != name or not name.endswith(".webp"):
            raise ValueError(f"Invalid packed image name: {name}")
        bucket = hashlib.sha256(name.encode()).digest()[0] % BUCKETS
        buckets.setdefault(bucket, []).append(name)
    result: dict = {"version": 1, "packs": {}, "images": {}}
    for bucket, members in sorted(buckets.items()):
        part, offset, digest = 0, 0, hashlib.sha256()

        def finish() -> None:
            if offset:
                key = f"{bucket:02x}-{part}"
                result["packs"][key] = {
                    "file": f"lesson-images-{key}.bin",
                    "size": offset,
                    "sha256": digest.hexdigest(),
                }

        for name in members:
            data = (image_root / name).read_bytes()
            if not data or len(data) > MAX_PACK_BYTES:
                raise ValueError(f"Image is empty or exceeds one media pack: {name}")
            if offset + len(data) > MAX_PACK_BYTES:
                finish()
                part, offset, digest = part + 1, 0, hashlib.sha256()
            with Image.open(io.BytesIO(data)) as image:
                width, height = image.size
            result["images"][name] = {
                "pack": f"{bucket:02x}-{part}", "offset": offset, "size": len(data),
                "width": width, "height": height,
                "sha256": hashlib.sha256(data).hexdigest(),
                "md5": hashlib.md5(data).hexdigest(),
            }
            digest.update(data)
            offset += len(data)
        finish()
    return result


def write_index(mobile_root: Path, names: list[str]) -> None:
    index = build_index(mobile_root / "assets" / "lesson-assets", names)
    (mobile_root / "src" / "generated" / "bundled-image-packs.json").write_text(
        json.dumps(index, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    requires = "\n".join(
        f"  '{key}': require('../assets/lesson-image-packs/{pack['file']}'),"
        for key, pack in index["packs"].items()
    )
    (mobile_root / "src" / "lessonImagePacks.ts").write_text(
        "// Generated by scripts/export_mobile_preview_lessons.py.\n"
        "// Metro bundles the complete offline course as bounded binary assets.\n"
        "export const LESSON_IMAGE_PACKS: Record<string, number> = {\n"
        + requires + "\n};\n", encoding="utf-8"
    )
